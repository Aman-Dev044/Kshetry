import fs from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(fs.readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);

// ---- collect rings as flat arrays, with bboxes ----
const rings = [];
for (const f of land.features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polys) {
    for (let i = 0; i < poly.length; i++) {
      const ring = poly[i];
      let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
      for (const [x, y] of ring) {
        if (x < minX) minX = x; if (x > maxX) maxX = x;
        if (y < minY) minY = y; if (y > maxY) maxY = y;
      }
      rings.push({ ring, minX, minY, maxX, maxY, hole: i > 0 });
    }
  }
}

function inRing(ring, px, py) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1], xj = ring[j][0], yj = ring[j][1];
    if ((yi > py) !== (yj > py) && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lon, lat) {
  let hit = false;
  for (const r of rings) {
    if (lon < r.minX || lon > r.maxX || lat < r.minY || lat > r.maxY) continue;
    if (inRing(r.ring, lon, lat)) { if (r.hole) return false; hit = true; }
  }
  return hit;
}

// ---- grid: equirectangular, lon -180..180, lat 84..-58 (drop Antarctica) ----
const W = 360, H = 150;
const LON0 = -180, LON1 = 180, LAT0 = 84, LAT1 = -58;
const bytes = new Uint8Array(Math.ceil((W * H) / 8));
let count = 0;
for (let y = 0; y < H; y++) {
  const lat = LAT0 + ((LAT1 - LAT0) * (y + 0.5)) / H;
  for (let x = 0; x < W; x++) {
    const lon = LON0 + ((LON1 - LON0) * (x + 0.5)) / W;
    if (isLand(lon, lat)) {
      const idx = y * W + x;
      bytes[idx >> 3] |= 1 << (idx & 7);
      count++;
    }
  }
  if (y % 25 === 0) process.stderr.write(`row ${y}\n`);
}

const b64 = Buffer.from(bytes).toString('base64');
const out = `// AUTO-GENERATED by scripts/gen-map.mjs — do not edit by hand.
// Equirectangular land bitmask: ${W}x${H} grid, lon ${LON0}..${LON1}, lat ${LAT0}..${LAT1}.
export const MAP_GRID = { w: ${W}, h: ${H}, lon0: ${LON0}, lon1: ${LON1}, lat0: ${LAT0}, lat1: ${LAT1} } as const;
export const MAP_MASK_B64 = "${b64}";
`;
fs.writeFileSync('src/data/world-mask.ts', out);
console.log(`land cells: ${count} / ${W * H}  (base64 ${b64.length} chars)`);
