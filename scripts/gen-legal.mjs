/**
 * Turns the four legal documents in the client's specification PDF into
 * `src/data/legal.ts`, preserving the firm's own wording verbatim.
 *
 *   node scripts/gen-legal.mjs <path-to-extracted-spec.txt>
 *
 * The source text is produced with pdfplumber (`x_tolerance=1.5`), which keeps
 * words intact where pypdf splits them across justified lines.
 */
import fs from "node:fs";

const SRC = process.argv[2];
if (!SRC) {
  console.error("usage: node scripts/gen-legal.mjs <spec.txt>");
  process.exit(1);
}

const lines = fs.readFileSync(SRC, "utf8").split(/\r?\n/);

/** Page furniture that the PDF repeats on every sheet. */
const NOISE = /^(Prepared by Adv\. Shaina Z\.|===== PAGE \d+ =====|KSHETRY & CO\.|LAW FIRM)\s*$/;

const HEADING = /^(\d{1,2})\.\s+([A-Z][A-Z0-9 ,&’'\-–—/().]{3,})\s*$/;

/** 1-indexed, inclusive line ranges taken from the extracted text. */
const DOCS = [
  { id: "disclaimer", title: "Website Disclaimer", from: 1813, to: 1968 },
  { id: "terms", title: "Terms of Use", from: 1975, to: 2265 },
  { id: "privacy", title: "Privacy Policy", from: 2271, to: 2711 },
];

function parse(from, to) {
  const sections = [];
  let current = null;

  for (let i = from - 1; i < to && i < lines.length; i++) {
    const raw = lines[i];
    const text = raw.trim();
    if (!text || NOISE.test(text)) continue;

    const m = text.match(HEADING);
    if (m) {
      current = { n: m[1], heading: titleCase(m[2]), body: [] };
      sections.push(current);
      continue;
    }

    if (!current) continue;

    // Short all-caps lines inside a section are sub-headings, not prose.
    if (text.length < 60 && text === text.toUpperCase() && /[A-Z]/.test(text)) {
      current.body.push({ kind: "sub", text: titleCase(text) });
      continue;
    }

    const last = current.body[current.body.length - 1];
    if (last && last.kind === "p" && !/[.:;]$/.test(last.text)) {
      last.text += " " + text;
    } else {
      current.body.push({ kind: "p", text });
    }
  }

  return sections.map((s) => ({
    n: s.n,
    heading: s.heading,
    body: s.body.map((b) => ({ ...b, text: tidy(b.text) })).filter((b) => b.text.length > 1),
  }));
}

const SMALL = new Set(["and", "or", "of", "to", "the", "in", "for", "a", "an", "with", "on", "by"]);
const KEEP = new Set(["UK", "EU", "US", "USA", "UAE", "GCC", "IT", "AI", "HR", "NRI", "CV"]);

function titleCase(s) {
  return s
    .toLowerCase()
    .split(/(\s+|[–—/-])/)
    .map((w, i) => {
      const up = w.toUpperCase();
      if (KEEP.has(up)) return up;
      if (!/[a-z]/.test(w)) return w;
      if (i > 0 && SMALL.has(w)) return w;
      return w.charAt(0).toUpperCase() + w.slice(1);
    })
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}

function tidy(s) {
  return s.replace(/\s+/g, " ").replace(/\s+([,.;:])/g, "$1").trim();
}

const docs = DOCS.map((d) => ({ id: d.id, title: d.title, sections: parse(d.from, d.to) }));

for (const d of docs) {
  console.log(`${d.id}: ${d.sections.length} sections`);
  if (!d.sections.length) console.warn(`  !! no sections parsed for ${d.id}`);
}

const out = `// AUTO-GENERATED by scripts/gen-legal.mjs from the client specification PDF.
// The firm's legal wording is reproduced verbatim — edit the source, not this file.

export type LegalBlock = { kind: "p" | "sub"; text: string };
export type LegalSection = { n: string; heading: string; body: LegalBlock[] };
export type LegalDoc = { id: string; title: string; sections: LegalSection[] };

export const LEGAL_DOCS: Record<string, LegalDoc> = ${JSON.stringify(
  Object.fromEntries(docs.map((d) => [d.id, d])),
  null,
  2,
)};
`;

fs.writeFileSync("src/data/legal.ts", out);
console.log("wrote src/data/legal.ts");
